test("network camera configuration persists without displaying credentials",async({page})=>{
  await login(page);
  await page.getByRole("navigation").getByRole("button",{name:"设备管理"}).click();
  await page.screenshot({path:"../outputs/platform-devices.png",fullPage:true});
  const device=await page.request.post(`${backend}/devices`,{headers,data:{name:"测试离线摄像头",url:"rtsp://127.0.0.1:9/video",username:"camera",password:"camera-test-secret",enabled:true}});
  expect(device.ok()).toBeTruthy();
  const record=await device.json();
  expect(JSON.stringify(record)).not.toContain("camera-test-secret");
  await page.reload();
  await page.getByRole("navigation").getByRole("button",{name:"设备管理"}).click();
  await expect(page.getByText("测试离线摄像头",{exact:true})).toBeVisible();
  await page.getByRole("navigation").getByRole("button",{name:"检测工作台"}).click();
  await page.getByRole("tab",{name:"实时监测"}).click();
  await page.getByLabel("摄像头来源").selectOption("network");
  await page.getByLabel("网络摄像头",{exact:true}).selectOption(record.id);
  await page.getByRole("button",{name:"连接设备",exact:true}).click();
  await expect(page.getByRole("alert")).toContainText(/无法连接|超时|停止/);
  await expect(page.getByRole("button",{name:"连接设备",exact:true})).toBeEnabled();
  expect(await page.locator("body").innerText()).not.toContain("camera-test-secret");
});

test("real local MJPEG preview infers and archives only the selected frame",async({page})=>{
  await login(page);
  const before=(await (await page.request.get(`${backend}/inspections?offset=0&limit=1`)).json()).total;
  const device=await (await page.request.post(`${backend}/devices`,{headers,data:{name:"本地测试视频流",url:"http://127.0.0.1:8002/stream",enabled:true}})).json();
  await page.getByRole("navigation").getByRole("button",{name:"检测工作台"}).click();
  await page.getByRole("tab",{name:"实时监测"}).click();
  await page.getByLabel("摄像头来源").selectOption("network");
  await page.getByLabel("网络摄像头",{exact:true}).selectOption(device.id);
  await page.getByRole("button",{name:"连接设备",exact:true}).click();
  await expect(page.getByAltText("网络摄像头实时预览")).toBeVisible();
  await page.getByRole("button",{name:"开始网络连续检测"}).click();
  await expect(page.getByAltText("网络摄像头模型标注结果")).toBeVisible();
  await page.getByRole("button",{name:"停止网络检测"}).click();
  await expect(page.getByRole("button",{name:"保存当前结果",exact:true})).toBeEnabled();
  expect((await (await page.request.get(`${backend}/inspections?offset=0&limit=1`)).json()).total).toBe(before);
  await page.screenshot({path:"../outputs/platform-network-camera.png",fullPage:true});
  await page.getByRole("button",{name:"保存当前结果",exact:true}).click();
  await expect(page.getByRole("button",{name:"当前结果已归档",exact:true})).toBeVisible();
  expect((await (await page.request.get(`${backend}/inspections?offset=0&limit=1`)).json()).total).toBe(before+1);
  await page.getByRole("navigation").getByRole("button",{name:"质检总览"}).click();
  await expect.poll(async()=>(await (await page.request.get(`${backend}/devices/${device.id}/status`)).json()).status).toBe("disconnected");
});
