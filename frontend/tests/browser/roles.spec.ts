import { test, expect } from "@playwright/test";

const backend = "http://localhost:8001/api/v1";
const headers = { Origin: "http://localhost:3001" };

test("role workspaces, employee activity, and layout comparison respect account permissions", async ({ page, browser }) => {
  await page.request.post(`${backend}/auth/login`, { headers, data: { username: "admin", password: "admin123" } });
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "管理工作台", exact: true })).toBeVisible();
  await page.screenshot({ path: "../outputs/roles-admin.png", fullPage: true });
  await page.getByRole("navigation").getByRole("button", { name: "系统设置", exact: true }).click();
  await page.getByRole("button", { name: "原版布局", exact: true }).click();
  await page.getByRole("navigation").getByRole("button", { name: "质检总览", exact: true }).click();
  await expect(page.getByRole("heading", { name: "看见细微，掌握全局。" })).toBeVisible();
  await page.screenshot({ path: "../outputs/roles-classic.png", fullPage: true });
  await page.getByRole("navigation").getByRole("button", { name: "系统设置", exact: true }).click();
  await page.getByRole("button", { name: "角色工作台", exact: true }).click();
  await page.getByRole("navigation").getByRole("button", { name: "用户与权限" }).click();
  const name = "operator" + Date.now();
  await page.getByRole("button", { name: "＋ 添加用户" }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("登录账号").fill(name);
  await dialog.getByLabel("显示名称").fill("员工验收");
  await expect(dialog.getByLabel("角色", { exact: true }).locator("option")).toHaveText(["总管理员", "员工"]);
  await dialog.getByLabel("角色", { exact: true }).selectOption("inspector");
  await dialog.getByLabel("初始密码（至少 8 位）").fill("employee123");
  await dialog.getByRole("button", { name: "保存", exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByLabel("搜索员工").fill(name);
  const employee = page.locator(".sv-user-row").filter({ hasText: name });
  await expect(employee).toContainText("员工");
  await page.screenshot({ path: "../outputs/roles-users.png", fullPage: true });

  const context = await browser.newContext({ baseURL: "http://localhost:3001", viewport: { width: 1440, height: 1000 } });
  try {
    const staff = await context.newPage();
    await staff.request.post(`${backend}/auth/login`, { headers, data: { username: name, password: "employee123" } });
    await staff.goto("/");
    await expect(staff.getByRole("heading", { name: "我的工作台", exact: true })).toBeVisible();
    await expect(staff.getByRole("navigation").getByRole("button", { name: "用户与权限" })).toHaveCount(0);
    await expect(staff.getByRole("navigation").getByRole("button", { name: "系统设置" })).toHaveCount(0);
    await staff.screenshot({ path: "../outputs/roles-employee.png", fullPage: true });
    expect((await staff.request.post(`${backend}/batches`, { headers, data: { code: name } })).ok()).toBeTruthy();
    const workspace = await (await staff.request.get(`${backend}/workspace`)).json();
    expect(workspace.logs.every((entry: { username: string }) => entry.username === name)).toBeTruthy();
    await staff.getByRole("button", { name: "界面设置", exact: true }).click();
    const appearance = staff.getByRole("dialog", { name: "界面设置", exact: true });
    await appearance.getByRole("button", { name: "原版布局", exact: true }).click();
    await appearance.getByRole("button", { name: "关闭详情", exact: true }).click();
    await expect(staff.getByRole("navigation").getByRole("button", { name: "用户与权限" })).toHaveCount(0);
    await staff.reload();
    await expect(staff.getByRole("heading", { name: "看见细微，掌握全局。" })).toBeVisible();
    await staff.getByRole("button", { name: "界面设置", exact: true }).click();
    await expect(staff.getByRole("button", { name: "原版布局", exact: true })).toHaveAttribute("aria-pressed", "true");
    await appearance.getByRole("button", { name: "角色工作台", exact: true }).click();
    await appearance.getByRole("button", { name: "关闭详情", exact: true }).click();
    for (const name of ["用户与权限","系统设置","操作日志","个人设置","我的操作"]) await expect(staff.getByRole("navigation").getByRole("button",{name,exact:true})).toHaveCount(0);
    await staff.setViewportSize({ width: 390, height: 844 });
    await expect(staff.getByRole("navigation", { name: "主导航" })).toBeHidden();
    await staff.getByRole("button", { name: "打开导航菜单", exact: true }).click();
    await staff.getByRole("navigation").getByRole("button", { name: "我的工作台" }).click();
    await expect(staff.getByRole("navigation", { name: "主导航" })).toBeHidden();
    expect(await staff.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
    await staff.screenshot({ path: "../outputs/roles-mobile.png", fullPage: true });

    await page.getByRole("button", { name: "刷新业务数据" }).click();
    await employee.getByRole("button", { name: "查看操作" }).click();
    await expect(page.getByRole("dialog")).toContainText("新建批次");
    await page.screenshot({ path: "../outputs/roles-activity.png", fullPage: true });
    await page.getByRole("button", { name: "关闭详情" }).click();
    await employee.getByRole("button", { name: "编辑权限" }).click();
    await dialog.getByLabel("角色", { exact: true }).selectOption("admin");
    await dialog.getByRole("button", { name: "保存", exact: true }).click();
    await expect(dialog).not.toBeVisible();
    expect((await staff.request.get(`${backend}/workspace`)).status()).toBe(401);
    await staff.request.post(`${backend}/auth/login`, { headers, data: { username: name, password: "employee123" } });
    await staff.goto("/");
    await expect(staff.getByRole("heading", { name: "管理工作台", exact: true })).toBeVisible();
    await employee.getByRole("button", { name: "编辑权限" }).click();
    await dialog.getByLabel("角色", { exact: true }).selectOption("inspector");
    await dialog.getByRole("button", { name: "保存", exact: true }).click();
    await expect(dialog).not.toBeVisible();
    expect((await staff.request.get(`${backend}/workspace`)).status()).toBe(401);
    await staff.request.post(`${backend}/auth/login`, { headers, data: { username: name, password: "employee123" } });
    await staff.goto("/");
    await expect(staff.getByRole("heading", { name: "我的工作台", exact: true })).toBeVisible();
    await staff.getByRole("button", { name: "打开导航菜单", exact: true }).click();
    await staff.getByRole("navigation").getByRole("button", { name: "生产", exact:true }).click();
    await expect(staff.getByRole("button", { name: "＋ 新建批次" })).toBeVisible();
  } finally { await context.close(); }
});
